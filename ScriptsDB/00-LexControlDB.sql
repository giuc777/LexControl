-- SP_Evento_ObtenerDelDia CORREGIDO (JOIN a PERSONA para asistentes)
CREATE OR ALTER PROCEDURE SP_Evento_ObtenerDelDia
    @Usuario_ID INT = NULL,
    @Fecha DATE = NULL
AS
BEGIN
    SET NOCOUNT ON;
    IF @Fecha IS NULL SET @Fecha = CAST(GETDATE() AS DATE);
    SELECT
        EB.ID, EB.Titulo, EB.Fecha, EB.HoraInicio, EB.HoraFin,
        EB.TipoEvento, EB.Ubicacion, EB.Prioridad, EB.ColorEvento,
        E.NoExpediente, P.NombreCompleto AS Cliente,
        EA.TipoAudiencia, EP.TipoPlazo, ED.TipoDiligencia,
        EE.Nombre AS EstadoNombre,
        STRING_AGG(UP.NombreCompleto, ', ') AS Asistentes
    FROM EVENTO_BASE EB
    LEFT JOIN EXPEDIENTE E ON EB.Expediente_ID = E.ID
    LEFT JOIN CLIENTE C ON EB.Cliente_ID = C.ID
    LEFT JOIN PERSONA P ON C.Persona_ID = P.ID
    LEFT JOIN EVENTO_AUDIENCIA EA ON EB.ID = EA.Evento_ID
    LEFT JOIN EVENTO_PLAZO EP ON EB.ID = EP.Evento_ID
    LEFT JOIN EVENTO_DILIGENCIA ED ON EB.ID = ED.Evento_ID
    LEFT JOIN ESTADO_EVENTO EE ON EB.Estado_ID = EE.ID
    LEFT JOIN EVENTO_ASISTENTES EAS ON EB.ID = EAS.Evento_ID
    LEFT JOIN USUARIO U ON EAS.Usuario_ID = U.ID
    LEFT JOIN PERSONA UP ON U.Persona_ID = UP.ID
    WHERE EB.Fecha = @Fecha
      AND (@Usuario_ID IS NULL OR EB.CreadoPor = @Usuario_ID OR EXISTS (
          SELECT 1 FROM EVENTO_ASISTENTES WHERE Evento_ID = EB.ID AND Usuario_ID = @Usuario_ID
      ))
      AND EB.Estado_ID = (SELECT ID FROM ESTADO_EVENTO WHERE Nombre = 'Pendiente')
    GROUP BY EB.ID, EB.Titulo, EB.Fecha, EB.HoraInicio, EB.HoraFin,
             EB.TipoEvento, EB.Ubicacion, EB.Prioridad, EB.ColorEvento,
             E.NoExpediente, P.NombreCompleto,
             EA.TipoAudiencia, EP.TipoPlazo, ED.TipoDiligencia, EE.Nombre
    ORDER BY EB.HoraInicio ASC;
END
