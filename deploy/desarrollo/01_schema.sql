-- 1.1 Agregar columna HashLegacy a USUARIO
--     Indica si el hash de la contraseña aún usa SHA256 (legacy)
IF NOT EXISTS (
    SELECT 1 FROM sys.columns
    WHERE object_id = OBJECT_ID('USUARIO') AND name = 'HashLegacy'
