-- 2.2 PERSONA
CREATE TABLE PERSONA (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    NombreCompleto NVARCHAR(100) NOT NULL,
    DPI NVARCHAR(20) NULL,
    TelefonoPrincipal NVARCHAR(20) NULL,
    EmailPrincipal NVARCHAR(100) NULL,
    Direccion NVARCHAR(200) NULL,
    FechaNacimiento DATE NULL,
    Genero CHAR(1) NULL,
    Activo BIT NOT NULL DEFAULT 1,
    FechaCreacion DATETIME NOT NULL DEFAULT GETDATE(),
    FechaModificacion DATETIME NULL,
    UsuarioCreacion_ID INT NULL,
    UsuarioModificacion_ID INT NULL,
    CONSTRAINT CHK_PERSONA_Genero CHECK (Genero IN ('M', 'F', 'O'))
);
CREATE INDEX IX_PERSONA_Nombre ON PERSONA(NombreCompleto);
-- Único FILTRADO: admite varios DPI nulos y conserva unicidad de DPIs reales.
CREATE UNIQUE INDEX UX_PERSONA_DPI ON PERSONA(DPI) WHERE DPI IS NOT NULL;
CREATE INDEX IX_PERSONA_Email ON PERSONA(EmailPrincipal);
CREATE INDEX IX_PERSONA_Activo ON PERSONA(Activo);
GO

